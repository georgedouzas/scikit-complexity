"""
# Parity automaton on the lamplighter group

The cells sit on a ball of radius 7 of the lamplighter group, the automaton group generated by `a = (a, b)(0 1)` and
`b = (a, b)`. Each cell takes the sum modulo 2 of itself and its neighbours at `a` and `b`, a linear rule over the field
of two elements, so a few ones spread into a growing, flickering pattern over the Diestel-Leader graph of the group.
"""

# %%
# The ball holds 964 elements on rings by word length, colored by their state.

import matplotlib.pyplot as plt

from skcomplex.core.analysis import automaton
from skcomplex.core.components.elements import GroupElement
from skcomplex.core.components.interactions import LocalRuleInteraction
from skcomplex.core.components.spaces import CayleySpace, MemoryNeighborhood
from skcomplex.core.components.systems import CompositeSystem
from skcomplex.core.engine.runtime import simulate
from skcomplex.core.engine.viz import RerunObserver
from skcomplex.core.specs import LinearRuleSpec
from skcomplex.systems.computer_science.automata import BinaryCellElement, LamplighterAutomatonSystem, lamplighter

SYSTEM = 'lamplighter_automaton'

observer = RerunObserver(SYSTEM, save_path=f'{SYSTEM}.rrd', blueprint='default')
trajectory = simulate(LamplighterAutomatonSystem(radius=7, density=0.1, random_state=0), observers=[observer])

# %%
# Ones over time and invertibility on a quotient
# ----------------------------------------------
# A linear rule maps sums of configurations to sums of images, so the pattern of a few ones is the sum of the
# patterns of single ones, and the number of ones fluctuates instead of settling. On the finite quotient of level 3,
# the group ring element `1 + a + b` is a matrix over GF(2), and its rank decides whether the automaton is invertible
# there.

alive = trajectory.values('cells.alive')
quotient = CayleySpace(lamplighter().PermGroupOnLevel(3)).prepare()
parity = CompositeSystem(
    elements=[GroupElement('cells', element=BinaryCellElement, space=quotient, on='sites')],
    interactions=[
        LocalRuleInteraction(
            'parity',
            target='cells',
            state='alive',
            rule=LinearRuleSpec((1, 1, 1), 'GF(2)'),
            neighborhood=MemoryNeighborhood(('1', 'a', 'b')),
        ),
    ],
)
invertible = automaton(parity, kind='injective').injective
fig, ax = plt.subplots(figsize=(6, 4))
ax.plot(trajectory.times, alive.sum(axis=1), 'o-')
ax.set_xlabel('step')
ax.set_ylabel('number of ones')
ax.set_title(f'Invertible on the quotient of {quotient.size_} elements: {invertible}')
plt.show()
