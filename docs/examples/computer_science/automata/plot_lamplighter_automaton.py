"""
# Parity automaton on the lamplighter group

The cells sit on a ball of radius 7 of the lamplighter group, the automaton group generated by `a = (a, b)(0 1)` and
`b = (a, b)`. Each cell takes the sum modulo 2 of itself and its neighbours at `a` and `b`, a linear rule over the field
of two elements, so a few ones spread into a growing, flickering pattern over the Diestel-Leader graph of the group.
"""

# %%
# The ball holds 964 elements on rings by word length, colored by their state.

import matplotlib.pyplot as plt

from skcomplex.analysis import AutomatonAnalysis
from skcomplex.core.spaces import CayleySpace, MemoryNeighborhood
from skcomplex.engine.runtime import Simulation
from skcomplex.engine.viz import RerunObserver
from skcomplex.models import create
from skcomplex.models.computer_science.automata import LinearAutomaton, lamplighter

MODEL = 'lamplighter_automaton'

system = create(MODEL, radius=7, density=0.1, random_state=0)
observer = RerunObserver(MODEL, save_path=f'{MODEL}.rrd', blueprint='default')
simulation = Simulation(system, observers=[observer]).check().run(until=20)

# %%
# Ones over time and invertibility on a quotient
# ----------------------------------------------
# A linear rule maps sums of configurations to sums of images, so the pattern of a few ones is the sum of the
# patterns of single ones, and the number of ones fluctuates instead of settling. On the finite quotient of level 3,
# the group ring element `1 + a + b` is a matrix over GF(2), and its rank decides whether the automaton is invertible
# there.

alive = simulation.trajectory_.values('cells.alive')
quotient = CayleySpace(lamplighter(), quotient=3).prepare()
parity = LinearAutomaton(quotient, MemoryNeighborhood(('1', 'a', 'b')), (1, 1, 1), 'GF(2)')
invertible = AutomatonAnalysis('injective').check().prepare(parity).run().injective_
fig, ax = plt.subplots(figsize=(6, 4))
ax.plot(simulation.trajectory_.times, alive.sum(axis=1), 'o-')
ax.set_xlabel('step')
ax.set_ylabel('number of ones')
ax.set_title(f'Invertible on the quotient of {quotient.size_} elements: {invertible}')
plt.show()
