"""Test the finitely generated groups: their constructors, their words, and the balls of their word problems."""

import sys

import pytest

from skcomplex.core.base import ValidationError, WordProblemError
from skcomplex.core.space import (
    GroupSpace,
    automaton_group,
    finitely_presented_group,
    matrix_group,
    parse_word,
    permutation_group,
)

GRIGORCHUK = {
    'a': ((None, None), (1, 0)),
    'b': (('a', 'c'), None),
    'c': (('a', 'd'), None),
    'd': ((None, 'b'), None),
}
LAMPLIGHTER = {'a': (('a', 'b'), (1, 0)), 'b': (('a', 'b'), None)}


def test_parse_word_reads_exponents_and_the_identity():
    """Test that a word with exponents expands into signed letters and that `1` is the empty word."""
    assert parse_word('a^2*b^-1', ('a', 'b')) == (1, 1, -2)
    assert parse_word('1', ('a',)) == ()


def test_parse_word_rejects_an_unknown_generator():
    """Test that a factor outside the generators raises an error naming the generators."""
    with pytest.raises(ValidationError, match='a, b'):
        parse_word('a*c', ('a', 'b'))


def test_matrix_group_balls_of_a_free_matrix_group():
    """Test that Sanov's matrices generate balls of radii 0 to 3 as large as those of the free group of rank 2."""
    group = matrix_group([[[1, 2], [0, 1]], [[1, 0], [2, 1]]], 'ZZ')
    assert [GroupSpace(group, ball=radius).size for radius in range(4)] == [1, 5, 17, 53]


def test_permutation_group_balls_of_the_symmetric_group():
    """Test that the transposition and the 3-cycle reach 4 elements within radius 1 and all 6 from radius 2 on."""
    group = permutation_group([[1, 0, 2], [1, 2, 0]])
    assert GroupSpace(group, ball=1).size == 4
    assert [GroupSpace(group, ball=radius).size for radius in (2, 3, 4)] == [6, 6, 6]
    assert GroupSpace(group).size == 6


def test_matrix_group_over_a_prime_field_is_finite():
    """Test that the group generated by elementary matrices over the field of 2 elements is all of GL(2, 2)."""
    group = matrix_group([[[1, 1], [0, 1]], [[1, 0], [1, 1]]], 'GF(2)')
    assert GroupSpace(group).size == 6


@pytest.mark.parametrize(
    ('generators', 'ring', 'message'),
    [
        ([[[2, 0], [0, 1]]], 'ZZ', 'not an invertible integer matrix'),
        ([[[1, 0], [0, 1]]], 'GF(4)', 'Unknown ring'),
        ([[[1, 0, 0]]], 'ZZ', 'square matrices'),
    ],
)
def test_matrix_group_rejects_bad_generators(generators, ring, message):
    """Test that a matrix group needs square matrices invertible over a known ring."""
    with pytest.raises(ValidationError, match=message):
        matrix_group(generators, ring)


def test_permutation_group_rejects_a_non_permutation():
    """Test that images that repeat a point are rejected."""
    with pytest.raises(ValidationError, match='permutes the same points'):
        permutation_group([[0, 0, 1]])


def test_automaton_group_rejects_an_unknown_section():
    """Test that a section that names no state is rejected with the states it may name."""
    with pytest.raises(ValidationError, match='Sections are states of a'):
        automaton_group({'a': (('z', None), (1, 0))})


def test_finitely_presented_group_balls_of_the_free_group_without_gap(monkeypatch):
    """Test that the free group of rank 2 has the ball sizes 1, 5, 17, and 53 without loading GAP."""
    monkeypatch.setitem(sys.modules, 'sage.all__sagemath_gap', None)
    space = GroupSpace(finitely_presented_group(['a', 'b']), ball=3)
    assert space.ball_sizes() == [1, 5, 17, 53]


def test_finitely_presented_group_balls_from_a_rewriting_system():
    """Test that the balls of BS(1, 2) match those of its affine representation, 1, 5, 17, 43, and 93."""
    group = finitely_presented_group(['a', 't'], ['t*a*t^-1*a^-2'])
    assert GroupSpace(group, ball=4).ball_sizes() == [1, 5, 17, 43, 93]


def test_finitely_presented_group_without_a_confluent_system_raises():
    """Test that a presentation Knuth-Bendix cannot complete raises an error that asks for a quotient."""
    relators = ['a*b*a^-1*b^-1*c^-1', 'a*c*a^-1*c^-1', 'b*c*b^-1*c^-1']
    group = finitely_presented_group(['a', 'b', 'c'], relators)
    with pytest.raises(WordProblemError, match='finite quotient'):
        GroupSpace(group, ball=3).ball_sizes()


def test_automaton_group_balls_of_the_lamplighter_group():
    """Test that the lamplighter automaton has the balls of the lamplighter group, 1, 5, 15, 39, and 92."""
    assert GroupSpace(automaton_group(LAMPLIGHTER), ball=4).ball_sizes() == [1, 5, 15, 39, 92]


def test_automaton_group_level_quotients():
    """Test that the Grigorchuk group acts on levels 1 to 3 of the binary tree through groups of 2, 8, and 128."""
    group = automaton_group(GRIGORCHUK)
    assert [GroupSpace(group, quotient=level).size for level in (1, 2, 3)] == [2, 8, 128]


def test_automaton_group_without_gap_raises(monkeypatch):
    """Test that an automaton group whose ball needs GAP names the package to install when GAP is missing."""
    monkeypatch.setitem(sys.modules, 'sage.all__sagemath_gap', None)
    with pytest.raises(ImportError, match='pip install passagemath-gap'):
        GroupSpace(automaton_group(GRIGORCHUK), ball=2).ball_sizes()


def test_level_quotient_needs_an_automaton_group():
    """Test that a level quotient of a permutation group raises an error naming automaton groups."""
    with pytest.raises(ValidationError, match='Only automaton groups'):
        GroupSpace(permutation_group([[1, 0]]), quotient=2).ball_sizes()
