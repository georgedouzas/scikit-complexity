"""Test the `_groups` module of `skcomplex.models.computer_science.automata`."""

from sage.all__sagemath_gap import libgap

from skcomplex.core.spaces import CayleySpace, MemoryNeighborhood
from skcomplex.models.computer_science.automata import (
    grigorchuk_group,
    heisenberg,
)

from .conftest import GRIGORCHUK_BALLS


def _site_of(space, word):
    """Return the site reached from the identity along the letters of a word."""
    return int(space._index_table(MemoryNeighborhood((word,)))[0, 0])


def test_grigorchuk_group_is_an_automaton_group():
    """Test that the Grigorchuk group acts on the binary tree and is generated by a, b, c, and d."""
    group = grigorchuk_group()
    assert libgap.IsTreeAutomorphismGroup(group)
    assert int(libgap.DegreeOfTree(group)) == 2
    assert CayleySpace(group, ball=1).check().prepare().generators_ == ('a', 'b', 'c', 'd')


def test_grigorchuk_growth():
    """Test that the balls of radii 0 to 5 hold 1 to 68 sites, all distinct elements as their level-12 actions show."""
    group = grigorchuk_group()
    ball = CayleySpace(group, ball=5).check().prepare()
    assert ball.ball_sizes_ == GRIGORCHUK_BALLS[:6]
    generators = libgap.GeneratorsOfGroup(group)
    keys = set()
    for word in ball.words_:
        element = libgap.One(group)
        for letter in ball._parse_word(word):
            element *= generators[abs(letter) - 1] ** (1 if letter > 0 else -1)
        keys.add(str(libgap.PermOnLevel(element, 12)))
    assert len(keys) == ball.size_


def test_grigorchuk_level_quotients_run_periodic_rules():
    """Test that the quotients of levels 1 to 4 hold 2, 8, 128, and 4096 sites and every cell reads inside them."""
    sizes = []
    for level in (1, 2, 3, 4):
        space = CayleySpace(grigorchuk_group().PermGroupOnLevel(level)).check().prepare()
        sizes.append(space.size_)
        assert (space._index_table(MemoryNeighborhood(('1', *space.generators_))) < space.size_).all()
    assert sizes == [2, 8, 128, 4096]


def test_heisenberg_commutator_is_central():
    """Test that the commutator of the Heisenberg generators commutes with both generators."""
    space = CayleySpace(heisenberg(), ball=6).check().prepare()
    commutator = 'a*b*a^-1*b^-1'
    for generator in ('a', 'b'):
        assert _site_of(space, f'{commutator}*{generator}') == _site_of(space, f'{generator}*{commutator}')
